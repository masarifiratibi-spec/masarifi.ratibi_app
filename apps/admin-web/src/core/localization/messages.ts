export type MessageKey = string;

function lookup(locale: Locale, key: MessageKey): string {
  let value: MessageTree | string = messages[locale];
  for (const part of key.split(".")) {
    if (!value || typeof value === "string") return key;
    value = value[part];
  }
  return typeof value === "string" ? value : key;
}

export function t(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}): string {
  return lookup(locale, key).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
